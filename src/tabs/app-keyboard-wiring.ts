/** Bind keyboard actions to explicitly typed active session services. */
import type { CliRenderer } from "@opentui/core";
import type { DiagnosticLogger } from "../diagnostics/logger.ts";
import type { AppScreenContext } from "../ui/app-screen-context.ts";
import { registerAppKeyboard } from "./app-keyboard.ts";
import type { KeyboardPorts } from "./app-keyboard-contracts.ts";

export function registerScreenKeyboard(
	screen: AppScreenContext,
	renderer: CliRenderer,
	logger: DiagnosticLogger,
): void {
	const s = screen.signals;
	const ports: KeyboardPorts = {
		abortActiveWork: screen.input.abortActiveWork,
		activateTab: screen.runtime.activateTab,
		activeRuntime: screen.runtime.activeRuntime,
		availableSubagentTargets: screen.inspector.availableSubagentTargets,
		backgroundSelection: screen.extras.backgroundSelection,
		clearMainDraft: screen.draft.clearMainDraft,
		closeBackgroundTask: screen.background.closeBackgroundTask,
		closeMemoryBrowser: screen.modal.closeMemoryBrowser,
		closeNotification: screen.subagent.closeNotification,
		closePromptMap: screen.modal.closePromptMap,
		closeSessionSelector: screen.settings.closeSessionSelector,
		closeSettings: screen.settings.closeSettings,
		closeSubagentInspector: screen.subagent.closeSubagentInspector,
		closeTodo: screen.subagent.closeTodo,
		commandSuggestionIndex: s.commandSuggestionIndex[0],
		commandSuggestions: screen.selectors.commandSuggestions,
		compactionExpanded: s.compactionExpanded[0],
		completeDialog: screen.modal.completeDialog,
		copySelection: screen.subagent.copySelection,
		cycleSubagent: screen.subagent.cycleSubagent,
		cycleThinkingEffort: screen.transcript.cycleThinkingEffort,
		dialog: s.dialog[0],
		dimensions: screen.extras.dimensions,
		displaySubagentTargets: screen.inspector.displaySubagentTargets,
		expandedPromptText: screen.draft.expandedPromptText,
		expandedTools: s.expandedTools[0],
		focusMainPrompt: screen.subagent.focusMainPrompt,
		forkPickerOpen: s.forkPickerOpen[0],
		getPrompt: screen.extras.getPrompt,
		getScroll: screen.extras.getScroll,
		getSubagentScroll: screen.extras.getSubagentScroll,
		insertSuggestedCommand: screen.transcript.insertSuggestedCommand,
		inspectSubagent: screen.runtime.inspectSubagent,
		logger,
		mcpView: s.mcpView[0],
		memoryBrowserOpen: s.memoryBrowserOpen[0],
		modelSelectorOpen: s.modelSelectorOpen[0],
		notificationDetailId: screen.extras.notificationDetailId,
		openMemoryBrowser: screen.modal.openMemoryBrowser,
		openModelSelector: screen.settings.openModelSelector,
		openPromptMap: screen.modal.openPromptMap,
		openSettings: screen.settings.openSettings,
		promptMapOpen: s.promptMapOpen[0],
		queueFollowUp: screen.input.queueFollowUp,
		renderer,
		requestPauseSubagent: screen.subagent.requestPauseSubagent,
		requestStopSubagent: screen.subagent.requestStopSubagent,
		restoreQueuedFollowUp: screen.input.restoreQueuedFollowUp,
		sessionSelectorOpen: s.sessionSelectorOpen[0],
		setAllThinkingExpanded: screen.selectors.setAllThinkingExpanded,
		setCommandSuggestionIndex: s.commandSuggestionIndex[1],
		setCompactionExpanded: s.compactionExpanded[1],
		setExpandedToolIds: screen.runtime.setExpandedToolIds,
		setExpandedTools: s.expandedTools[1],
		setInspectSubagent: screen.runtime.setInspectSubagent,
		setMcpView: s.mcpView[1],
		setModelSelectorOpen: s.modelSelectorOpen[1],
		setPromptCursorOffset: s.promptCursorOffset[1],
		setSelectedTargetKey: screen.runtime.setSelectedTargetKey,
		setSettingsRoute: s.settingsRoute[1],
		setSidebarEnabled: s.sidebarEnabled[1],
		setSubagentSelectorOpen: s.subagentSelectorOpen[1],
		settingsRoute: s.settingsRoute[0],
		skillSelectorOpen: s.skillSelectorOpen[0],
		streaming: screen.selectors.streaming,
		subagentSelectorOpen: s.subagentSelectorOpen[0],
		subagentsAvailable: screen.selectors.subagentsAvailable,
		syncMainDraft: screen.draft.syncMainDraft,
		tabManager: s.tabManager,
		thinkingExpanded: s.thinkingExpanded[0],
		toast: screen.extras.toast,
		todoDetailId: screen.extras.todoDetailId,
		updateScrollPosition: screen.scroll.updateScrollPosition,
	};
	registerAppKeyboard(ports);
}
